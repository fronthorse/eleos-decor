create or replace function public.search_products(
  p_search_query text default '',
  p_category text default null,
  p_sort text default 'relevance',
  p_limit integer default 12,
  p_offset integer default 0
)
returns table (
  id text,
  title text,
  description text,
  price text,
  image_url text,
  category text,
  created_at timestamptz,
  rank real,
  total_count bigint
)
language sql
stable
security invoker
set search_path = public
as $$
  with search_input as (
    select
      nullif(trim(coalesce(p_search_query, '')), '') as query_text,
      nullif(trim(coalesce(p_category, '')), '') as category_filter,
      greatest(coalesce(p_limit, 12), 1) as limit_rows,
      greatest(coalesce(p_offset, 0), 0) as offset_rows
  ),
  matched_products as (
    select
      p.id::text,
      p.title::text,
      p.description::text,
      p.price::text,
      p.image_url::text,
      p.category::text,
      p.created_at,
      case
        when search_input.query_text is null then 0::real
        else ts_rank_cd(
          p.search_vector,
          websearch_to_tsquery('english', search_input.query_text)
        )
      end as rank,
      nullif(regexp_replace(p.price::text, '[^0-9.]', '', 'g'), '')::numeric
        as price_value
    from public.products p
    cross join search_input
    where (
      search_input.category_filter is null
      or search_input.category_filter = 'All'
      or p.category = search_input.category_filter
    )
    and (
      search_input.query_text is null
      or p.search_vector @@ websearch_to_tsquery('english', search_input.query_text)
    )
  ),
  counted_products as (
    select
      matched_products.*,
      count(*) over() as total_count
    from matched_products
  )
  select
    counted_products.id,
    counted_products.title,
    counted_products.description,
    counted_products.price,
    counted_products.image_url,
    counted_products.category,
    counted_products.created_at,
    counted_products.rank,
    counted_products.total_count
  from counted_products
  cross join search_input
  order by
    case when p_sort = 'price_low' then counted_products.price_value end asc nulls last,
    case when p_sort = 'price_high' then counted_products.price_value end desc nulls last,
    case when p_sort = 'oldest' then counted_products.created_at end asc,
    case when p_sort = 'newest' then counted_products.created_at end desc,
    counted_products.rank desc,
    counted_products.created_at desc
  limit (select limit_rows from search_input)
  offset (select offset_rows from search_input);
$$;
revoke all on function public.search_products(text,text,text,integer,integer) from public;
grant execute on function public.search_products(text,text,text,integer,integer) to anon, authenticated, service_role;
-- Optional admin analytics helper.
-- Run in Supabase SQL Editor to calculate dashboard metrics in one
-- database-side aggregate query instead of many client-side requests.

create or replace function public.get_admin_analytics()
returns table (
  total_products bigint,
  total_reviews bigint,
  average_rating numeric,
  total_inquiries bigint,
  pending_inquiries bigint,
  contacted_inquiries bigint,
  payment_pending_inquiries bigint,
  processing_inquiries bigint,
  confirmed_inquiries bigint,
  fulfilled_inquiries bigint,
  cancelled_inquiries bigint,
  estimated_revenue numeric
)
language sql
stable
as $$
  select
    (select count(*) from public.products) as total_products,
    (select count(*) from public.reviews) as total_reviews,
    coalesce((select round(avg(rating::numeric), 1) from public.reviews), 0) as average_rating,
    (select count(*) from public.checkout_inquiries) as total_inquiries,
    (
      select count(*) from public.checkout_inquiries
      where status = 'new'
    ) as pending_inquiries,
    (
      select count(*) from public.checkout_inquiries
      where status = 'contacted'
    ) as contacted_inquiries,
    (
      select count(*) from public.checkout_inquiries
      where status = 'payment_pending'
    ) as payment_pending_inquiries,
    (
      select count(*) from public.checkout_inquiries
      where status = 'processing'
    ) as processing_inquiries,
    (
      select count(*) from public.checkout_inquiries
      where status = 'paid'
    ) as confirmed_inquiries,
    (
      select count(*) from public.checkout_inquiries
      where status = 'delivered'
    ) as fulfilled_inquiries,
    (
      select count(*) from public.checkout_inquiries
      where status = 'cancelled'
    ) as cancelled_inquiries,
    coalesce(
      (
        select sum(total_amount::numeric)
        from public.checkout_inquiries
        where status = any(array['paid', 'processing', 'delivered'])
      ),
      0
    ) as estimated_revenue;
$$;
